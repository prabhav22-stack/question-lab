def get_tma_signal(course_code: str, unit_number: int) -> float:
    """
    Returns TMA signal weight for unit:
    1.0 for 20M Category A question
    0.5 for 10M Category B/C question
    0.0 if absent
    """
    course_tma = CURRENT_CYCLE_TMA_QUESTIONS.get(course_code, [])
    max_val = 0.0
    for q in course_tma:
        if q['unit'] == unit_number:
            val = 1.0 if q['category'] == 'A' else 0.5
            if val > max_val:
                max_val = val
    return max_val

def get_tma_subtopics(course_code: str, unit_number: int) -> list:
    course_tma = CURRENT_CYCLE_TMA_QUESTIONS.get(course_code, [])
    return [q['subtopic'] for q in course_tma if q['unit'] == unit_number]
